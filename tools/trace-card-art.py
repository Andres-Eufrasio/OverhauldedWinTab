"""Regenerate embedded vector outlines from the two visual references.

Usage: python trace-card-art.py --logo logoMain.png --back back_high.jpg
Requires numpy and opencv-python-headless (development only).
Does not download or bundle the reference bitmaps. Runtime uses only contours.
"""
import argparse
from pathlib import Path

import cv2
import numpy as np

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--logo', type=Path, required=True)
parser.add_argument('--back', type=Path, required=True)
args = parser.parse_args()
source = Path(__file__).resolve().parents[1] / 'OverhauldedWinTab.wh.cpp'


def encode(mask, epsilon, minimum_area):
    contours, _ = cv2.findContours(
        mask.astype('uint8') * 255, cv2.RETR_LIST, cv2.CHAIN_APPROX_SIMPLE)
    values = []
    for contour in contours:
        if cv2.contourArea(contour) < minimum_area:
            continue
        points = cv2.approxPolyDP(contour, epsilon, True).reshape(-1, 2)
        if len(points) < 3:
            continue
        values.append(len(points))
        values.extend(int(v) for v in points.ravel())
    return values


lines = [
    '// BEGIN GENERATED CARD ART DATA',
    '// Generated by tools/trace-card-art.py; do not edit the contour arrays.',
    '// References (viewed before tracing):',
    '// https://www.saikikusuo.com/image/index/logoMain.png (552 x 195)',
    '// https://images.ygoprodeck.com/images/cards/back_high.jpg (428 x 614)',
    '// Logo: original black Japanese title, white keyline, and red wide Psi.',
    '// Back: original copper frame and full-height amber/black vortex.',
]


def emit_array(name, mask, epsilon, minimum_area):
    values = encode(mask, epsilon, minimum_area)
    assert values and all(0 <= v < 32768 for v in values)
    lines.append(f'static const short {name}[] = {{')
    for offset in range(0, len(values), 24):
        lines.append('    ' + ','.join(map(str, values[offset:offset + 24])) + ',')
    lines.append('};')
    return name


def emit_layers(name, layers):
    lines.append(f'static const CardArtLayer {name}[] = {{')
    for color, array in layers:
        lines.append(f'    {{0xFF{color:06X}, {array}, ARRAYSIZE({array})}},')
    lines.append('};')


logo = cv2.imread(str(args.logo), cv2.IMREAD_UNCHANGED)
assert logo is not None and logo.shape == (195, 552, 4), 'Unexpected logo reference'
opaque = logo[:, :, 3] >= 128
dark = opaque & (logo[:, :, :3].max(2) < 100)
red = opaque & (logo[:, :, 2] > 120) & (logo[:, :, 1] < 100)
logo_layers = []
for index, (color, mask) in enumerate([
    (0xFFFFFF, opaque), (0x221815, dark), (0xE60012, red),
]):
    logo_layers.append((color, emit_array(f'kSaikiOutline{index}', mask, .45, 2)))
emit_layers('kSaikiLogoLayers', logo_layers)

back = cv2.imread(str(args.back))
assert back is not None and back.shape == (614, 428, 3), 'Unexpected card-back reference'
cv2.setRNGSeed(42)
_, labels, colors = cv2.kmeans(
    back.reshape(-1, 3).astype('float32'), 9, None,
    (cv2.TERM_CRITERIA_EPS + cv2.TERM_CRITERIA_MAX_ITER, 60, .2),
    4, cv2.KMEANS_PP_CENTERS)
order = np.argsort(colors.sum(1))
ranks = np.empty(9, dtype=int)
ranks[order] = np.arange(9)
ranks = ranks[labels.reshape(back.shape[:2])]
back_layers = []
# Cumulative contours (alternate fill) retain holes and avoid seams between
# adjacent color regions. Ignore subpixel specks invisible at card size.
for index in range(1, 9):
    b, g, r = (int(round(v)) for v in colors[order[index]])
    color = (r << 16) | (g << 8) | b
    array = emit_array(f'kVortexOutline{index}', ranks >= index, .9, 6)
    back_layers.append((color, array))
emit_layers('kYugiohVortexLayers', back_layers)
lines.append('// END GENERATED CARD ART DATA')

text = source.read_text(encoding='utf-8')
start = text.index('// BEGIN GENERATED CARD ART DATA')
end = text.index('// END GENERATED CARD ART DATA', start)
end += len('// END GENERATED CARD ART DATA')
source.write_text(text[:start] + '\n'.join(lines) + text[end:], encoding='utf-8', newline='\n')
print(f'Generated 3 logo layers and 8 vortex layers in {source.name}')
